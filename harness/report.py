#!/usr/bin/env python3
"""Build a results table from results/*.json. The table is generated, not typed.

Why this exists: a hand-written table in a README is unverifiable the moment a
number changes. Every cell here comes from a harness report file, and each file
records the model string, prompt mode, item count and wall time that produced it.

    python3 harness/report.py                    # results/*.json -> results/TABLE.md
    python3 harness/report.py --out -            # print markdown to stdout
    python3 harness/report.py --require-full     # fail unless every run has >= N items
"""

from __future__ import annotations

import argparse
import json
import pathlib
import statistics
import sys

MIN_ITEMS_FOR_CLAIM = 5  # per task; 20-item dev set is a smoke test, not a benchmark


def load(results_dir: pathlib.Path) -> list[dict]:
    reports = []
    for path in sorted(results_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            print(f"skipping {path.name}: not JSON", file=sys.stderr)
            continue
        if "summary" not in data or "rows" not in data:
            print(f"skipping {path.name}: not a harness report", file=sys.stderr)
            continue
        data["_file"] = path.name
        reports.append(data)
    return reports


def overall(report: dict) -> tuple[float, float, float]:
    ratios = [r["ratio"] for r in report["rows"]]
    return statistics.fmean(ratios), min(ratios), max(ratios)


def task_names(reports: list[dict]) -> list[str]:
    names = set()
    for rep in reports:
        for row in rep["summary"]:
            names.add(row["task"])
    return sorted(names)


def render(reports: list[dict]) -> str:
    if not reports:
        return ("_No results yet._ Run `python3 harness/cli.py ... --out results/<name>.json`, "
                "then regenerate this table.\n")

    tasks = task_names(reports)
    lines: list[str] = []
    lines.append("| model | prompt | n | " + " | ".join(tasks) + " | overall | blank | wall |")
    lines.append("|" + "---|" * (4 + len(tasks) + 2))

    for rep in reports:
        by_task = {t: next((s for s in rep["summary"] if s["task"] == t), None) for t in tasks}
        cells = []
        for t in tasks:
            s = by_task[t]
            cells.append(f"{s['score']:.3f}" if s else "–")
        mean, _, _ = overall(rep)
        n = rep.get("items", 0)
        flag = "" if n >= MIN_ITEMS_FOR_CLAIM * len(tasks) else " ⚠"
        lines.append(
            f"| {rep['model']} | {rep.get('prompt_mode', 'raw')} | {n}{flag} | "
            + " | ".join(cells)
            + f" | **{mean:.3f}** | {rep.get('blank_responses', 0)} | {rep.get('elapsed_s', 0)}s |"
        )

    lines.append("")
    lines.append("### 95% bootstrap CI per task")
    lines.append("")
    lines.append("| model | prompt | " + " | ".join(tasks) + " |")
    lines.append("|" + "---|" * (2 + len(tasks)))
    for rep in reports:
        cells = []
        for t in tasks:
            s = next((x for x in rep["summary"] if x["task"] == t), None)
            cells.append(f"[{s['ci95'][0]:.2f}, {s['ci95'][1]:.2f}]" if s else "–")
        lines.append(f"| {rep['model']} | {rep.get('prompt_mode', 'raw')} | " + " | ".join(cells) + " |")

    # Prompt-condition deltas, the number H1 is actually about.
    by_key = {(r["model"], r.get("prompt_mode", "raw")): r for r in reports}
    deltas = []
    for (model, mode), rep in by_key.items():
        if mode != "raw":
            continue
        partner = by_key.get((model, "doctrine"))
        if not partner:
            continue
        raw_mean, _, _ = overall(rep)
        doc_mean, _, _ = overall(partner)
        deltas.append((model, raw_mean, doc_mean, doc_mean - raw_mean))
    if deltas:
        lines.append("")
        lines.append("### doctrine − raw (the prompt-only reference)")
        lines.append("")
        lines.append("| model | raw | doctrine | Δ |")
        lines.append("|---|---|---|---|")
        for model, raw_mean, doc_mean, delta in deltas:
            lines.append(f"| {model} | {raw_mean:.3f} | {doc_mean:.3f} | {delta:+.3f} |")

    lines.append("")
    lines.append(f"_Generated by `harness/report.py` from {len(reports)} result file(s). "
                 f"Runs under {MIN_ITEMS_FOR_CLAIM * len(tasks)} items are dev-set scale and "
                 f"cannot support a per-task claim._")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="results/TABLE.md")
    ap.add_argument("--min-items", type=int, default=0,
                    help="fail if any report has fewer items than this")
    args = ap.parse_args()

    reports = load(pathlib.Path(args.results))
    if args.min_items:
        short = [r for r in reports if r.get("items", 0) < args.min_items]
        if short:
            for r in short:
                print(f"{r['_file']}: {r.get('items', 0)} items < --min-items {args.min_items}",
                      file=sys.stderr)
            return 1

    body = render(reports)
    if args.out == "-":
        print(body, end="")
        return 0

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(f"wrote {out} from {len(reports)} report(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())